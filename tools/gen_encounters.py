#!/usr/bin/env python3
"""Generate knowledge/encounters.py from a pret/pokefirered checkout.

Usage: python tools/gen_encounters.py [path-to-pokefirered] > knowledge/encounters.py

LAND_LEVELS maps (map_bank, map_id) -> (min level, rate-weighted average level, max level) of the wild
Pokémon found in that map's tall grass in LeafGreen. grind() uses it to pick a route whose wild levels fit the
Pokémon being trained (a high-level patch levels the ace; it is a poor place to level a L10).
"""
import json
import os
import sys


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    const_to_gn = {}
    for gi, gname in enumerate(groups["group_order"]):
        if not gname.startswith("gMapGroup_"):
            continue
        for ni, dname in enumerate(groups[gname]):
            mj = f"{pf}/data/maps/{dname}/map.json"
            if os.path.exists(mj):
                const_to_gn[json.load(open(mj))["id"]] = (gi, ni)
    wild = json.load(open(f"{pf}/src/data/wild_encounters.json"))["wild_encounter_groups"][0]
    rates = next(f["encounter_rates"] for f in wild["fields"] if f["type"] == "land_mons")
    out = {}
    for e in wild["encounters"]:
        if not e["base_label"].endswith("LeafGreen") or "land_mons" not in e:
            continue
        gn = const_to_gn.get(e["map"])
        mons = e["land_mons"]["mons"]
        if gn is None or len(mons) != len(rates):
            continue
        avg = sum(r * (m["min_level"] + m["max_level"]) / 2 for r, m in zip(rates, mons)) / sum(rates)
        out[gn] = (min(m["min_level"] for m in mons), round(avg, 1), max(m["max_level"] for m in mons))
    print('"""GENERATED by tools/gen_encounters.py from the pokefirered decomp — do not edit.\n'
          '(map_bank, map_id) -> (min, average, max) wild level in LeafGreen tall grass."""\n')
    print("LAND_LEVELS: dict[tuple[int, int], tuple[int, float, int]] = {")
    for gn in sorted(out):
        print(f"    {gn!r}: {out[gn]!r},  # {next(k for k, v in const_to_gn.items() if v == gn)}")
    print("}")


if __name__ == "__main__":
    main()
