#!/usr/bin/env python3
"""Generate knowledge/area_facts.py from a pret/pokefirered checkout.

Usage: python tools/gen_area_facts.py [path-to-pokefirered] > knowledge/area_facts.py

For every map that has trainers or items: (map_bank, map_id) -> (readable name, trainer count, ((item, x, y), …), (exits…)) — item balls
(the item read from the script that gives it) and hidden items — plus MAP_IDS: map directory name -> (bank, id), so hand-written
guidance can name maps the way the decomp does and never mistype an id.
"""
import json
import os
import re
import sys


def readable(d: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", d.replace("_", " "))
    s = re.sub(r"\b(B?\d) F\b", r"\1F", s)                       # "Victory Road 2 F" -> "Victory Road 2F"
    return s.replace("Mart", "Poké Mart").replace("Pokemon", "Pokémon").strip()


def item_name(const: str, labels: dict) -> str:
    return labels.get(const) or const.replace("ITEM_", "").replace("_", " ").title()


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    labels = {i["itemId"]: i["english"].title().replace("Poke", "Poké") for i in json.load(open(f"{pf}/src/data/items.json"))["items"]}
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    ball_src = open(f"{pf}/data/scripts/item_ball_scripts.inc").read()
    ball_item = {m.group(1): m.group(2) for m in re.finditer(r"^(\w+)::\n\s*finditem (ITEM_\w+)", ball_src, re.M)}
    ids, facts = {}, {}
    for bank, g in enumerate(groups["group_order"]):
        for mid, d in enumerate(groups.get(g, [])):
            ids[d] = (bank, mid)
    for d, key in ids.items():
        mj = f"{pf}/data/maps/{d}/map.json"
        if not os.path.exists(mj):
            continue
        data = json.load(open(mj))
        trainers = sum(1 for o in data.get("object_events", []) if o.get("trainer_type", "TRAINER_TYPE_NONE") != "TRAINER_TYPE_NONE")
        items = []
        for o in data.get("object_events", []):
            if "ITEM_BALL" in o.get("graphics_id", ""):
                items.append((item_name(ball_item[o["script"]], labels) if o["script"] in ball_item else "an item", int(o["x"]), int(o["y"])))
        for b in data.get("bg_events", []):
            if b.get("type") == "hidden_item" or "item" in b:
                items.append((item_name(str(b.get("item", "ITEM_NONE")), labels) + " (hidden)", int(b["x"]), int(b["y"])))
        exits, pads = [], []
        warps = data.get("warp_events", [])
        for i, w in enumerate(warps):
            dest = w["dest_map"].replace("MAP_", "")
            exits.append(dest)
            if w["dest_map"] == data["id"]:                       # a warp pad inside the same map (Sabrina's gym, Silph Co. teleporters)
                j = int(w["dest_warp_id"]) if str(w["dest_warp_id"]).isdigit() else -1
                if 0 <= j < len(warps):
                    pads.append((int(w["x"]), int(w["y"]), int(warps[j]["x"]), int(warps[j]["y"])))
        if trainers or items or pads:
            facts[key] = (readable(d), trainers, tuple(items), tuple(dict.fromkeys(exits)), tuple(pads))
    print('"""GENERATED by tools/gen_area_facts.py from the pokefirered decomp — do not edit.\n'
          'Per map with trainers, items or in-map warp pads: (name, trainer count, ((item, x, y), …), warp destinations, ((from x, y, to x, y), …) pads); MAP_IDS: decomp dir name -> (bank, id)."""\n')
    print("AREA_FACTS: dict[tuple[int, int], tuple] = {")
    for k in sorted(facts):
        print(f"    {k!r}: {facts[k]!r},")
    print("}\n")
    print("MAP_IDS: dict[str, tuple[int, int]] = {")
    for d in sorted(ids):
        print(f"    {d!r}: {ids[d]!r},")
    print("}")


if __name__ == "__main__":
    main()
