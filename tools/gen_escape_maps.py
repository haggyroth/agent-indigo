#!/usr/bin/env python3
"""Generate knowledge/escape_maps.py from a pret/pokefirered checkout.

Usage: python tools/gen_escape_maps.py [path-to-pokefirered] > knowledge/escape_maps.py

ESCAPABLE: maps where Escape Rope and Dig work (map.json "allow_escaping" — caves, forests, dungeons).
TELEPORT_OK: maps where Teleport (and Fly) work (map_type route / town / city / ocean route — outdoors).
"""
import json
import os
import sys

OUTDOOR = {"MAP_TYPE_ROUTE", "MAP_TYPE_TOWN", "MAP_TYPE_CITY", "MAP_TYPE_OCEAN_ROUTE"}


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    esc, tele = [], []
    for bank, gname in enumerate(groups["group_order"]):
        for mid, name in enumerate(groups[gname]):
            data = json.load(open(f"{pf}/data/maps/{name}/map.json"))
            if data.get("allow_escaping"):
                esc.append((bank, mid))
            if data.get("map_type") in OUTDOOR:
                tele.append((bank, mid))
    print('"""GENERATED by tools/gen_escape_maps.py from the pokefirered decomp — do not edit.\n'
          'Where Escape Rope / Dig (ESCAPABLE) and Teleport / Fly (TELEPORT_OK) work, as (map_bank, map_id)."""\n')
    for label, rows in (("ESCAPABLE", esc), ("TELEPORT_OK", tele)):
        print(f"{label}: frozenset[tuple[int, int]] = frozenset({{")
        for i in range(0, len(rows), 8):
            print("    " + ", ".join(str(r) for r in rows[i:i + 8]) + ",")
        print("})\n")


if __name__ == "__main__":
    main()
