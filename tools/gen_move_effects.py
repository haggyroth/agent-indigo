#!/usr/bin/env python3
"""Generate knowledge/move_effects.py from a pret/pokefirered checkout.

Usage: python tools/gen_move_effects.py [path-to-pokefirered] > knowledge/move_effects.py

MOVE_FX maps the move name (as game.constants.MOVE_NAMES yields it) to
(effect, accuracy, priority, secondary effect chance, target) straight from gBattleMoves. `effect` is the decomp
EFFECT_* name without its prefix (HIT, OHKO, DREAM_EATER, MEAN_LOOK, ...); accuracy 0 means "never misses".
knowledge.move_semantics turns these into expected damage and per-move guidance.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from game.constants import MOVE_NAMES   # noqa: E402


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in
           re.finditer(r"#define MOVE_(\w+)\s+(\d+)", open(f"{pf}/include/constants/moves.h").read())}
    txt = open(f"{pf}/src/data/battle_moves.h").read()
    out = {}
    for m in re.finditer(r"\[MOVE_(\w+)\]\s*=\s*\{(.*?)\n    \}", txt, re.S):
        name, body = m.group(1), m.group(2)
        mid = ids.get(name)
        if not mid or mid not in MOVE_NAMES:
            continue
        g = lambda pat: re.search(pat, body).group(1)   # noqa: E731
        out[MOVE_NAMES[mid]] = (g(r"\.effect = EFFECT_(\w+)"), int(g(r"\.accuracy = (\d+)")),
                                int(g(r"\.priority = (-?\d+)")), int(g(r"\.secondaryEffectChance = (\d+)")),
                                g(r"\.target = MOVE_TARGET_(\w+)"))
    print('"""GENERATED by tools/gen_move_effects.py from the pokefirered decomp — do not edit.\n'
          'move name -> (effect, accuracy, priority, secondary effect chance, target)."""\n')
    print("MOVE_FX: dict[str, tuple[str, int, int, int, str]] = {")
    for k in sorted(out):
        print(f"    {k!r}: {out[k]!r},")
    print("}")


if __name__ == "__main__":
    main()
