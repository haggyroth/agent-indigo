#!/usr/bin/env python3
"""Generate knowledge/exclusives.py (the Kanto Pokémon only FireRed's wild tables hold) from a pret/pokefirered checkout.

Usage: python tools/gen_exclusives.py [path-to-pokefirered] > knowledge/exclusives.py

A species is a FireRed exclusive when it appears in a FireRed wild-encounter table (land / water / rock smash / fishing) and in none of LeafGreen's, and is not itself an evolution (Arbok,
Gloom, Golduck, Weezing and Seadra turn up in FireRed's tables too, but a LeafGreen player evolves them from a base). FIRERED_ONLY: species id -> (the lowest level it is found at in FireRed,
where that is): Ekans, Oddish, Psyduck, Growlithe, Shellder, Scyther, Electabuzz. A LeafGreen player gets one by trading with a FireRed player (tool: `link_trade`)."""
import json
import os
import re
import sys

FIELDS = ("land_mons", "water_mons", "rock_smash_mons", "fishing_mons")


def place(map_const: str) -> str:
    name = map_const.removeprefix("MAP_").replace("_", " ").title().replace("Ssanne", "S.S. Anne").replace("Pokemon", "Pokémon")
    return re.sub(r"(?<=[a-z])(?=\d)", " ", name)


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    sp = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    enc = json.load(open(f"{pf}/src/data/wild_encounters.json"))["wild_encounter_groups"][0]["encounters"]
    found: dict[str, dict[int, tuple]] = {"FireRed": {}, "LeafGreen": {}}
    for e in enc:
        ver = "FireRed" if "FireRed" in e["base_label"] else "LeafGreen" if "LeafGreen" in e["base_label"] else None
        if ver is None:
            continue
        for f in FIELDS:
            for m in e.get(f, {}).get("mons", []):
                sid = sp.get(m["species"].removeprefix("SPECIES_"), 0)
                if 0 < sid <= 151 and (sid not in found[ver] or m["min_level"] < found[ver][sid][0]):
                    found[ver][sid] = (m["min_level"], place(e["map"]))
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    from knowledge.dex_sources import EVOLVES_FROM                              # generated from the same decomp (tools/gen_dex_sources.py)
    only = {s: v for s, v in sorted(found["FireRed"].items()) if s not in found["LeafGreen"] and s not in EVOLVES_FROM}
    print('"""Kanto Pokémon only FireRed\'s wild tables hold. GENERATED by tools/gen_exclusives.py from the pokefirered decomp — do not edit."""\n')
    print("# species id -> (lowest level it is found at in FireRed, where)")
    print("FIRERED_ONLY: dict[int, tuple[int, str]] = {")
    for s, (lv, where) in only.items():
        print(f"    {s}: ({lv}, {where!r}),")
    print("}")


if __name__ == "__main__":
    main()
