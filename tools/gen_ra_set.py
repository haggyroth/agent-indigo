#!/usr/bin/env python3
"""Generate knowledge/ra_set.py (the RetroAchievements set for Pokémon LeafGreen, game 788) from the official Web API (#358).

Usage: python tools/gen_ra_set.py > knowledge/ra_set.py

The credentials are read, in order, from the environment (RA_USERNAME, RA_API_KEY) or from the macOS Keychain entry `retroachievements` (its account is the username, its password the key).
They go to retroachievements.org and nowhere else: the key is never printed, logged, written to a file or echoed in an error message. The generated file is PUBLIC set data (titles,
descriptions, points and types) — no user fields — so CI and other contributors need no key.

The API's `MemAddr` is only an MD5 hash of each achievement's condition logic (all 128 checked, #358), not the logic itself, so the set cannot drive an rcheevos-style evaluator: what the
agent checks for each achievement is mapped by hand (knowledge/ra_map.py, later) against its own flags, badges, Pokédex and bag. The hashes are left out."""
import json
import os
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request

GAME_ID = 788
EXPECTED = (128, 781)                                        # achievements, points: the set as the owner saw it on the page (#358)


def credentials() -> tuple[str, str]:
    user, key = os.environ.get("RA_USERNAME", ""), os.environ.get("RA_API_KEY", "")
    if not key:
        try:
            key = subprocess.run(["security", "find-generic-password", "-s", "retroachievements", "-w"], capture_output=True, text=True, check=True).stdout.strip()
            if not user:
                attrs = subprocess.run(["security", "find-generic-password", "-s", "retroachievements"], capture_output=True, text=True, check=True).stdout
                user = next((line.split("=", 1)[1].strip().strip('"') for line in attrs.splitlines() if '"acct"' in line), "")
        except (OSError, subprocess.CalledProcessError):
            pass
    if not (user and key):
        sys.exit("no RetroAchievements credentials: set RA_USERNAME and RA_API_KEY, or add a Keychain item named 'retroachievements'")
    return user, key


def fetch(user: str, key: str) -> dict:
    # The API authenticates with query parameters only (z = username, y = web API key); HTTPS keeps them off the wire. Errors are reported by status alone — never with the URL.
    url = "https://retroachievements.org/API/API_GetGameExtended.php?" + urllib.parse.urlencode({"z": user, "y": key, "i": GAME_ID})
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "agent-indigo-ra-import"}), timeout=60) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        sys.exit(f"RetroAchievements answered HTTP {e.code}")
    except (urllib.error.URLError, TimeoutError, ValueError) as e:
        sys.exit(f"could not read the set ({type(e).__name__})")


def main():
    data = fetch(*credentials())
    ach = data.get("Achievements") or {}
    rows = sorted(ach.values(), key=lambda a: (a.get("DisplayOrder", 0), a["ID"]))
    points = sum(int(a["Points"]) for a in rows)
    print(f"# {data.get('Title')!r}: {len(rows)} achievements, {points} points (expected {EXPECTED[0]} / {EXPECTED[1]})", file=sys.stderr)
    print('"""The RetroAchievements set for Pokémon LeafGreen. GENERATED by tools/gen_ra_set.py from the official Web API — do not edit. Public set data only."""\n')
    print(f"GAME_ID = {GAME_ID}")
    print(f"TITLE = {data.get('Title')!r}")
    print("\n# (id, title, description, points, type) in the set's display order; type is '', 'progression', 'win_condition' or 'missable'")
    print("ACHIEVEMENTS: tuple[tuple[int, str, str, int, str], ...] = (")
    for a in rows:
        print(f"    ({int(a['ID'])}, {a['Title']!r}, {a['Description']!r}, {int(a['Points'])}, {(a.get('type') or '')!r}),")
    print(")")


if __name__ == "__main__":
    main()
