#!/usr/bin/env python3
"""Generate knowledge/held_items_data.py from a pret/pokefirered checkout.

Usage: python tools/gen_held_items.py [path-to-pokefirered] > knowledge/held_items_data.py

HELD_ITEMS: {item id: (display name, HOLD_EFFECT constant, effect param)} for every item with a battle effect when held.
"""
import json
import os
import re
import sys


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define (ITEM_\w+)\s+(\d+)", open(f"{pf}/include/constants/items.h").read())}
    items = json.load(open(f"{pf}/src/data/items.json"))["items"]
    out = {}
    for it in items:
        if it["holdEffect"] != "HOLD_EFFECT_NONE" and it["itemId"] in ids:
            out[ids[it["itemId"]]] = (it["english"].title().replace("'S", "'s"), it["holdEffect"][len("HOLD_EFFECT_"):], it["holdEffectParam"])
    print('"""GENERATED by tools/gen_held_items.py from the pokefirered decomp — do not edit.\n'
          'Items with a battle effect when held: item id -> (name, effect, param)."""\n')
    print("HELD_ITEMS: dict[int, tuple[str, str, int]] = {")
    for k in sorted(out):
        print(f"    {k}: {out[k]!r},")
    print("}")


if __name__ == "__main__":
    main()
