"""Regenerate knowledge/seafoam_data.py from a local pret/pokefirered checkout (Seafoam Islands B3F: the boulder floor that stops B4F's current).

    python tools/gen_seafoam.py [path-to-pokefirered] > knowledge/seafoam_data.py

B3F's lower-left room has four boulders and two fall holes ((6,18), (9,18)). A boulder pushed through a hole is removed there and revealed on B4F
(FLAG_HIDE_SEAFOAM_B4F_BOULDER_1/2 cleared); when B4F is entered with BOTH revealed the map swaps to LAYOUT_SEAFOAM_ISLANDS_B4F_CURRENT_STOPPED, which has calm water
all the way to Articuno's platform (the original layout has strong currents that sweep you away). Route 20's OnTransition resets the boulders (3-6 shown) until B4F is stopped."""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import gen_regions as g      # noqa: E402

B3F, B4F = "SeafoamIslands_B3F", "SeafoamIslands_B4F"
MAPS = {"MAP_SEAFOAM_ISLANDS_1F": (1, 83), "MAP_SEAFOAM_ISLANDS_B1F": (1, 84), "MAP_SEAFOAM_ISLANDS_B2F": (1, 85), "MAP_SEAFOAM_ISLANDS_B3F": (1, 86), "MAP_SEAFOAM_ISLANDS_B4F": (1, 87)}
HOLE_BEHAVIOR = 0x66          # MB_FALL_WARP


def main(pf):
    maps, _c2g, layouts = g.load(pf)
    attrs = g.tileset_attrs(pf)
    d = json.load(open(f"{pf}/data/maps/{B3F}/map.json"))
    L = layouts[d["layout"]]
    w, h = L["width"], L["height"]
    raw = open(f"{pf}/{L['blockdata_filepath']}", "rb").read()
    prim, sec = attrs[L["primary_tileset"]], attrs[L["secondary_tileset"]]
    rows, elev, holes = [], [], []
    for y in range(h):
        r, e = "", ""
        for x in range(w):
            v = raw[(y * w + x) * 2] | (raw[(y * w + x) * 2 + 1] << 8)
            mid = v & 0x3FF
            arr, idx = (prim, mid) if mid < g.NUM_PRIMARY else (sec, mid - g.NUM_PRIMARY)
            beh = arr[idx] & 0x1FF if idx < len(arr) else 0
            r += "#" if (v >> 10) & 3 else "."
            e += "%x" % (v >> 12)
            if beh == HOLE_BEHAVIOR:
                holes.append((x, y))
        rows.append(r)
        elev.append(e)
    warps = [(wv["x"], wv["y"]) for wv in d["warp_events"]]
    # the boulders Route 20's OnTransition shows (FLAG_HIDE_SEAFOAM_B3F_BOULDER_3..6): the movable ones with a Strength script
    boulders = [(o["x"], o["y"]) for o in d["object_events"] if "BOULDER" in o["graphics_id"] and o["script"] == "EventScript_StrengthBoulder"]
    flags = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"#define (FLAG_\w+)\s+(0x[0-9A-Fa-f]+)\b", open(f"{pf}/include/constants/flags.h").read())}
    hide = {(o["x"], o["y"]): flags[o["flag"]] for o in d["object_events"] if "BOULDER" in o["graphics_id"] and o["script"] == "EventScript_StrengthBoulder"}
    revealed = [flags["FLAG_HIDE_SEAFOAM_B4F_BOULDER_1"], flags["FLAG_HIDE_SEAFOAM_B4F_BOULDER_2"]]
    a = json.load(open(f"{pf}/data/maps/{B4F}/map.json"))
    articuno = next((o["x"], o["y"]) for o in a["object_events"] if "ARTICUNO" in o["graphics_id"])
    stairs = next((wv["x"], wv["y"]) for wv in a["warp_events"] if wv["dest_map"] == "MAP_SEAFOAM_ISLANDS_B3F" and wv["dest_warp_id"] == "3")
    print('"""GENERATED by tools/gen_seafoam.py from the pokefirered decomp — do not edit. See that file for what the data means."""')
    print(f"B3F_ROWS = {rows!r}".replace("', '", "',\n    '").replace("[", "[\n    ", 1))
    print(f"B3F_ELEV = {elev!r}".replace("', '", "',\n    '").replace("[", "[\n    ", 1))
    print(f"B3F_WARPS = {warps!r}")
    print(f"B3F_HOLES = {holes!r}")
    print(f"B3F_BOULDERS = {boulders!r}          # shown while the current is not stopped")
    print(f"B3F_BOULDER_FLAGS = {hide!r}      # boulder tile -> its FLAG_HIDE_* (set once it has fallen through a hole)")
    print(f"B4F_REVEAL_FLAGS = {revealed!r}      # cleared when a B3F boulder falls: both clear = the current stops")
    print(f"STOPPED_FLAG_B4F = {flags['FLAG_STOPPED_SEAFOAM_B4F_CURRENT']:#x}")
    print(f"ARTICUNO_TILE = {articuno!r}")
    print(f"B4F_STAIRS = {stairs!r}      # the B4F tile of the ladder up to B3F (arrives at B3F (12, 9))")


if __name__ == "__main__":
    main(os.path.expanduser(sys.argv[1]) if len(sys.argv) > 1 else os.path.expanduser("~/Projects/pokefirered"))
