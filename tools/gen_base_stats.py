#!/usr/bin/env python3
"""Generate knowledge/base_stats.py from a pret/pokefirered checkout.

Usage: python tools/gen_base_stats.py [path-to-pokefirered] > knowledge/base_stats.py

BASE_STATS maps the internal species id to ((HP, Atk, Def, Spe, SpA, SpD) base stats, (HP, Atk, Def, Spe, SpA, SpD) EV yield).
knowledge.mon_quality uses the base stats to project real stats from IVs / EVs / nature, and the EV yield to say what a
defeated species trains.
"""
import os
import re
import sys


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in
           re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    txt = open(f"{pf}/src/data/pokemon/species_info.h").read()
    out = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\] =\n    \{(.*?)\n    \}", txt, re.S):
        name, body = m.group(1), m.group(2)
        if name not in ids or ids[name] == 0:
            continue
        g = lambda k: int(re.search(rf"\.{k} = (\d+)", body).group(1))   # noqa: E731
        base = tuple(g(k) for k in ("baseHP", "baseAttack", "baseDefense", "baseSpeed", "baseSpAttack", "baseSpDefense"))
        ev = tuple(g(k) for k in ("evYield_HP", "evYield_Attack", "evYield_Defense", "evYield_Speed",
                                  "evYield_SpAttack", "evYield_SpDefense"))
        out[ids[name]] = (base, ev, name)
    print('"""GENERATED by tools/gen_base_stats.py from the pokefirered decomp — do not edit.\n'
          'species id -> ((HP, Atk, Def, Spe, SpA, SpD) base stats, (…) EV yield)."""\n')
    print("BASE_STATS: dict[int, tuple[tuple[int, ...], tuple[int, ...]]] = {")
    for sid in sorted(out):
        base, ev, name = out[sid]
        print(f"    {sid}: ({base!r}, {ev!r}),  # {name}")
    print("}")


if __name__ == "__main__":
    main()
