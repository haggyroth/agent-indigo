#!/usr/bin/env python3
"""Generate knowledge/levelup_learnsets.py (the Kanto Pokémon's level-up moves) from a pret/pokefirered checkout.

Usage: python tools/gen_levelup_learnsets.py [path-to-pokefirered] > knowledge/levelup_learnsets.py

LEVEL_UP: species id -> ((level, move id), ...) in the game's order, for species 1..151 (the same table FireRed and LeafGreen share)."""
import os
import re
import sys


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    species = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    moves = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define MOVE_(\w+)\s+(\d+)", open(f"{pf}/include/constants/moves.h").read())}
    sets = {}
    for m in re.finditer(r"static const u16 (s\w+LevelUpLearnset)\[\] = \{(.*?)LEVEL_UP_END", open(f"{pf}/src/data/pokemon/level_up_learnsets.h").read(), re.S):
        sets[m.group(1)] = tuple((int(lv), moves[mv]) for lv, mv in re.findall(r"LEVEL_UP_MOVE\((\d+),\s*MOVE_(\w+)\)", m.group(2)))
    out = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\]\s*=\s*(s\w+LevelUpLearnset)", open(f"{pf}/src/data/pokemon/level_up_learnset_pointers.h").read()):
        sid = species.get(m.group(1), 0)
        if 0 < sid <= 151:
            out[sid] = sets[m.group(2)]
    print('"""Kanto Pokémon level-up moves. GENERATED by tools/gen_levelup_learnsets.py from the pokefirered decomp — do not edit."""\n')
    print("# species id -> ((level, move id), ...) in the game's order")
    print("LEVEL_UP: dict[int, tuple[tuple[int, int], ...]] = {")
    for sid in sorted(out):
        print(f"    {sid}: ({', '.join(f'({lv}, {mv})' for lv, mv in out[sid])},),")
    print("}")


if __name__ == "__main__":
    main()
