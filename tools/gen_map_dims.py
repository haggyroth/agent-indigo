#!/usr/bin/env python3
"""Regenerate knowledge/map_dims.py (map width x height in tiles) from a local pret/pokefirered checkout.

Usage:
    python tools/gen_map_dims.py [path-to-pokefirered] > knowledge/map_dims.py

Keys are (map_bank, map_id), the same as knowledge/map_graph.py. Used to estimate how far apart two places are in tiles."""
import json
import os
import sys


def build(pf: str) -> dict:
    layouts = {l["id"]: (int(l["width"]), int(l["height"])) for l in json.load(open(f"{pf}/data/layouts/layouts.json"))["layouts"] if "id" in l}
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    out = {}
    for gi, gname in enumerate(n for n in groups["group_order"] if n.startswith("gMapGroup_")):
        for ni, dname in enumerate(groups[gname]):
            mj = f"{pf}/data/maps/{dname}/map.json"
            if os.path.exists(mj):
                lay = json.load(open(mj)).get("layout")
                if lay in layouts:
                    out[(gi, ni)] = layouts[lay]
    return out


if __name__ == "__main__":
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    dims = build(pf)
    w = sys.stdout.write
    w('"""Map sizes in tiles, (width, height) by (map_bank, map_id).\n\nGENERATED by tools/gen_map_dims.py from the pret/pokefirered decomp layouts."""\n\n')
    w("MAP_DIMS: dict[tuple[int, int], tuple[int, int]] = {\n")
    for k in sorted(dims):
        w(f"    {k}: {dims[k]},\n")
    w("}\n")
