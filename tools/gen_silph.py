"""Regenerate knowledge/silph_data.py from a local pret/pokefirered checkout (Silph Co.: 11 floors of warps, teleport pads and card-key doors).

    python tools/gen_silph.py [path-to-pokefirered] > knowledge/silph_data.py

The map blockdata is the OPEN layout; each floor's OnLoad script closes the doors whose flag is unset (`call_if_unset FLAG_SILPH_nF_DOOR_k,
EventScript_CloseNFDoorK`), and those Close scripts are lists of `setmetatile x, y, id, collision`. So per floor: collision rows with every door open,
plus DOORS = [(flag, ((x, y), ...closed collision tiles))]. A door is opened by facing one of its tiles with the Card Key and pressing A."""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_mansion import BUTTON as _BUTTON, collision_rows, warp_behaviors      # noqa: E402

BUTTON = {**_BUTTON, 0x67: None}      # Silph Co.'s teleport pads (3F/4F/5F/7F/8F/9F/10F/11F) fire when stepped on
TRIGGERS = set(BUTTON)

FLOORS = [f"SilphCo_{n}F" for n in range(1, 12)] + ["SilphCo_Elevator"]
FLAGS = {}


def door_flags(pf):
    for m in re.finditer(r"#define (FLAG_SILPH_\w+)\s+(0x[0-9A-F]+)", open(f"{pf}/include/constants/flags.h").read()):
        FLAGS[m.group(1)] = int(m.group(2), 16)


def close_scripts(pf):
    """{CloseXFDoorK: [((x, y), blocked)]}"""
    text = open(f"{pf}/data/scripts/silphco_doors.inc").read()
    out = {}
    for m in re.finditer(r"EventScript_(Close\w+Door\w*)::[^\n]*\n(.*?)\n\treturn", text, re.S):
        tiles = []
        for line in m.group(2).splitlines():
            t = re.match(r"\s*setmetatile\s+(\d+),\s*(\d+),\s*(\w+),\s*(\d)", line)
            if t and t.group(4) == "1":
                tiles.append((int(t.group(1)), int(t.group(2))))
        out[m.group(1)] = tiles
    return out


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))["gMapGroup_Dungeons"]
    ids = {n: (1, groups.index(n)) for n in FLOORS}
    door_flags(pf)
    closes = close_scripts(pf)
    out = sys.stdout
    out.write('"""Silph Co. floors: collision (doors OPEN), card-key doors, warps. GENERATED by tools/gen_silph.py — do not edit."""\n\n')
    out.write("FLOORS: dict = {\n")
    warps_all, maps = {}, {}
    for name in FLOORS:
        m, rows = collision_rows(pf, name)
        key = ids[name]
        maps[name] = m
        text = open(f"{pf}/data/maps/{name}/scripts.inc").read()
        doors = []
        for fm in re.finditer(r"call_if_unset (FLAG_SILPH_\w+), EventScript_(\w+)", text):
            doors.append((FLAGS[fm.group(1)], tuple(closes[fm.group(2)])))
        out.write(f"    {key}: {{\n        'name': {name.split('_')[1]!r},\n        'rows': (\n")
        for r in rows:
            out.write(f"            {r!r},\n")
        out.write("        ),\n")
        lift = [(w["x"], w["y"]) for w in m["warp_events"] if w["dest_map"] == "MAP_SILPH_CO_ELEVATOR"]
        out.write(f"        'doors': {doors!r},\n        'elevator': {lift!r},      # the lift doorway: stepping on it leaves the floor, so routes keep off it\n    }},\n")
        warps_all[key] = m["warp_events"]
    out.write("}\n\n")
    out.write("# ((bank, id), x, y) of a warp tile -> ((destination bank, id), arrival x, y, button to press ON the tile or None = fires when stepped on);\n")
    out.write("# None destination = out to Saffron City. Arrival-only tiles are left out.\n")
    out.write("WARPS: dict = {\n")
    by_map = {f"MAP_SILPH_CO_{n.split('_')[1]}": (ids[n], warps_all[ids[n]]) for n in FLOORS}
    names = {ids[n]: n for n in FLOORS}
    for key, wl in sorted(warps_all.items()):
        beh = warp_behaviors(pf, names[key])
        for w in wl:
            if beh[(w["x"], w["y"])] not in TRIGGERS:
                continue
            dest = w["dest_map"]
            if dest in by_map:
                dkey, dwl = by_map[dest]
                dw = dwl[int(w["dest_warp_id"])]
                out.write(f"    ({key!r}, {w['x']}, {w['y']}): ({dkey!r}, {dw['x']}, {dw['y']}, {BUTTON[beh[(w['x'], w['y'])]]!r}),\n")
            elif dest == "MAP_SAFFRON_CITY":
                out.write(f"    ({key!r}, {w['x']}, {w['y']}): None,\n")
    out.write("}\n")


if __name__ == "__main__":
    main()
