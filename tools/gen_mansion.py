"""Regenerate knowledge/mansion_data.py from a local pret/pokefirered checkout (the Pokémon Mansion's statue switches).

    python tools/gen_mansion.py [path-to-pokefirered] > knowledge/mansion_data.py

The Mansion has ONE global switch (FLAG_POKEMON_MANSION_SWITCH_STATE 0x26C). Pressing a statue on any floor flips it, and every floor then
swaps its barrier tiles (data/scripts/pokemon_mansion.inc: PressSwitch_<floor> / ResetSwitch_<floor> are `setmetatile x, y, id, collision`
lists). So each floor has two collision grids: the map's own (flag clear) and that grid with the PressSwitch overrides (flag set)."""
import json
import os
import re
import struct
import sys

FLOORS = (("PokemonMansion_1F", "1F"), ("PokemonMansion_2F", "2F"), ("PokemonMansion_3F", "3F"), ("PokemonMansion_B1F", "B1F"))


# Stairs and arrow warps are DIRECTIONAL: you stand on the tile and press the arrow's button (the game's TryArrowWarp); a fall warp (hole)
# fires when you step on it. {behaviour: button to press, or None}
BUTTON = {0x62: "Right", 0x63: "Left", 0x64: "Up", 0x65: "Down", 0x66: None, 0x6C: "Right", 0x6D: "Left", 0x6E: "Right", 0x6F: "Left"}
TRIGGERS = set(BUTTON)      # door / fall-warp (hole) / stairs behaviours that fire when stepped on; a warp event on any other tile
                                         # (0x00 / 0x08: the landing spot of a hole or a stairs) is ARRIVAL ONLY — stepping on it does nothing


def _attrs(path):
    raw = open(path, "rb").read()
    return [struct.unpack_from("<I", raw, 4 * i)[0] & 0x1FF for i in range(len(raw) // 4)]


def _snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name.replace("gTileset_", "")).lower()


def warp_behaviors(pf, map_name):
    """{(x, y): metatile behaviour} for every warp event tile of the map."""
    m = json.load(open(f"{pf}/data/maps/{map_name}/map.json"))
    layouts = json.load(open(f"{pf}/data/layouts/layouts.json"))["layouts"]
    L = next(x for x in layouts if x.get("id") == m["layout"])
    prim = _attrs(f"{pf}/data/tilesets/primary/{_snake(L['primary_tileset'])}/metatile_attributes.bin")
    sec = _attrs(f"{pf}/data/tilesets/secondary/{_snake(L['secondary_tileset'])}/metatile_attributes.bin")
    raw = open(os.path.join(pf, L["blockdata_filepath"]), "rb").read()
    out = {}
    for w in m["warp_events"]:
        mid = struct.unpack_from("<H", raw, 2 * (w["y"] * L["width"] + w["x"]))[0] & 0x3FF
        out[(w["x"], w["y"])] = prim[mid] if mid < 640 else sec[mid - 640]
    return out


def collision_rows(pf, map_name):
    m = json.load(open(f"{pf}/data/maps/{map_name}/map.json"))
    layouts = json.load(open(f"{pf}/data/layouts/layouts.json"))["layouts"]
    L = next(x for x in layouts if x.get("id") == m["layout"])
    W, H = L["width"], L["height"]
    raw = open(os.path.join(pf, L["blockdata_filepath"]), "rb").read()
    cells = [struct.unpack_from("<H", raw, 2 * i)[0] for i in range(W * H)]
    rows = ["".join("#" if (cells[y * W + x] >> 10) & 3 else "." for x in range(W)) for y in range(H)]
    return m, rows


def press_overrides(pf):
    """{floor suffix: {(x, y): blocked}} from the PressSwitch_<floor> scripts."""
    text = open(f"{pf}/data/scripts/pokemon_mansion.inc").read()
    out = {}
    for m in re.finditer(r"PokemonMansion_EventScript_PressSwitch_(\w+)::\n(.*?)\n\treturn", text, re.S):
        floor, body = m.group(1), m.group(2)
        tiles = {}
        for line in body.splitlines():
            t = re.match(r"\s*setmetatile\s+(\d+),\s*(\d+),\s*(\w+),\s*(\d)", line)
            if t:
                tiles[(int(t.group(1)), int(t.group(2)))] = bool(int(t.group(4)))
        out[floor] = tiles
    return out


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))["gMapGroup_Dungeons"]
    ids = {n: (1, groups.index(n)) for n, _ in FLOORS}
    press = press_overrides(pf)
    out = sys.stdout
    out.write('"""Pokémon Mansion collision grids for both switch states + warps + statues. GENERATED by tools/gen_mansion.py — do not edit."""\n\n')
    out.write("FLOORS: dict = {\n")
    warps_all = {}
    for name, suffix in FLOORS:
        m, rows = collision_rows(pf, name)
        key = ids[name]
        out.write(f"    {key}: {{\n        'name': {suffix!r},\n        'rows': (\n")
        for r in rows:
            out.write(f"            {r!r},\n")
        out.write("        ),\n")
        out.write(f"        'press': {dict(sorted(press.get(suffix, {}).items()))!r},\n")
        statues = [(b['x'], b['y']) for b in m.get('bg_events', []) if b.get('script', '').endswith('EventScript_Statue')]
        out.write(f"        'statues': {statues!r},\n    }},\n")
        warps_all[key] = m["warp_events"]
    out.write("}\n\n")
    out.write("# ((bank, id), x, y) of a warp tile -> ((destination bank, id), arrival x, y, button to press ON the tile or None = fires when stepped on); arrival = the destination map's warp #dest_warp_id\n")
    out.write("WARPS: dict = {\n")
    by_map = {}
    for name, _s in FLOORS:
        by_map[f"MAP_POKEMON_MANSION_{name.split('_')[1]}"] = (ids[name], warps_all[ids[name]])
    names = {ids[n]: n for n, _ in FLOORS}
    for key, wl in sorted(warps_all.items()):
        beh = warp_behaviors(pf, names[key])
        for w in wl:
            if beh[(w["x"], w["y"])] not in TRIGGERS:
                continue                                     # arrival-only tile
            dest = w["dest_map"]
            if dest in by_map:
                dkey, dwl = by_map[dest]
                dw = dwl[int(w["dest_warp_id"])]
                out.write(f"    ({key!r}, {w['x']}, {w['y']}): ({dkey!r}, {dw['x']}, {dw['y']}, {BUTTON[beh[(w['x'], w['y'])]]!r}),\n")
            elif dest == "MAP_CINNABAR_ISLAND":
                out.write(f"    ({key!r}, {w['x']}, {w['y']}): None,        # out to Cinnabar Island\n")
    out.write("}\n")


if __name__ == "__main__":
    main()
