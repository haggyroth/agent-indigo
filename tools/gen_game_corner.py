#!/usr/bin/env python3
"""Generate knowledge/game_corner_data.py from a pret/pokefirered checkout (the LeafGreen branch of every .ifdef).

Usage: python tools/gen_game_corner.py [path-to-pokefirered] > knowledge/game_corner_data.py

PRIZE_CLERKS: [(kind, map_bank, map_id, clerk_x, clerk_y, [(menu_index, item_or_species_id, coins, level_or_0)])] for the
Celadon Prize Corner's three clerks — kind 'mon' | 'tm' | 'item' — in the order the game's multichoice lists them.
COIN_LOTS: [(coins, yen)] the Game Corner's coin clerk sells. COIN_CASE: (item id, event flag, where it comes from).
"""
import json
import os
import re
import sys

GAME_CORNER, PRIZE_ROOM, RESTAURANT = "CeladonCity_GameCorner", "CeladonCity_GameCorner_PrizeRoom", "CeladonCity_Restaurant"


def leafgreen_only(text: str) -> str:
    """Resolve .ifdef FIRERED / .ifdef LEAFGREEN / .else / .endif blocks, keeping the LeafGreen side."""
    out, stack = [], []          # stack of (keep_this_branch_for_leafgreen, parent_keeps)
    for line in text.split("\n"):
        t = line.strip()
        if t.startswith(".ifdef"):
            want = t.split()[1] == "LEAFGREEN"
            parent = all(k for k in stack)
            stack.append(want)
            continue
        if t == ".else":
            stack[-1] = not stack[-1]
            continue
        if t == ".endif":
            stack.pop()
            continue
        if all(stack):
            out.append(line)
    return "\n".join(out)


def block(text, label):
    m = re.search(rf"^{label}::\n(.*?)(?=^\w+::|\Z)", text, re.S | re.M)
    return m.group(1) if m else ""


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define ((?:ITEM|SPECIES)_\w+)\s+(\d+)", open(f"{pf}/include/constants/items.h").read()
                                                          + open(f"{pf}/include/constants/species.h").read())}
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    where = {m: (bank, mid) for bank, g in enumerate(groups["group_order"]) for mid, m in enumerate(groups.get(g, []))}
    text = leafgreen_only(open(f"{pf}/data/maps/{PRIZE_ROOM}/scripts.inc").read())
    events = json.load(open(f"{pf}/data/maps/{PRIZE_ROOM}/map.json"))["object_events"]
    out = []
    for kind, clerk_label, choose_label in (("mon", "PrizeClerkMons", "ChoosePrizeMon"), ("tm", "PrizeClerkTMs", "ChoosePrizeTM"),
                                            ("item", "PrizeClerkItems", "ChoosePrizeItem")):
        ev = next(e for e in events if e["script"].endswith(clerk_label))
        body = block(text, f"{PRIZE_ROOM}_EventScript_{choose_label}")
        rows = []
        for idx, label in re.findall(r"case (\d+), (\w+)", body):
            if "EndPrizeExchange" in label:
                continue
            b = block(text, label)
            v1 = re.search(r"setvar VAR_TEMP_1, (\w+)", b)
            v2 = re.search(r"setvar VAR_TEMP_2, (\d+)", b)
            if not (v1 and v2):
                continue
            level = 0
            if kind == "mon":
                species = v1.group(1)
                give = next((block(text, l) for l in re.findall(r"case %s,\s+(\w+)" % species, text)), "")
                lv = re.search(r"givemon VAR_TEMP_1, (\d+)", give)
                level = int(lv.group(1)) if lv else 0
            rows.append((int(idx), ids[v1.group(1)], int(v2.group(1)), level))
        out.append((kind, *where[PRIZE_ROOM], int(ev["x"]), int(ev["y"]), rows))
    gc = open(f"{pf}/data/maps/{GAME_CORNER}/scripts.inc").read()
    lots = sorted((int(c), int(y)) for y, c in re.findall(r"checkmoney (\d+)\n.*?\n\s*addcoins (\d+)", gc, re.S))   # menu order: small lot first
    clerk = next(e for e in json.load(open(f"{pf}/data/maps/{GAME_CORNER}/map.json"))["object_events"] if e["script"].endswith("CoinsClerk"))
    flag = int(re.search(r"#define FLAG_GOT_COIN_CASE\s+(0x[0-9A-Fa-f]+)", open(f"{pf}/include/constants/flags.h").read()).group(1), 16)
    slots = [(b["x"], b["y"], b["script"].split("EventScript_")[-1]) for b in json.load(open(f"{pf}/data/maps/{GAME_CORNER}/map.json"))["bg_events"]
             if b.get("script") and "SlotMachine" in b["script"]]
    print('"""GENERATED by tools/gen_game_corner.py from the pokefirered decomp (LeafGreen side) — do not edit.\n'
          'The Celadon Game Corner: coin purchases, the three Prize Corner clerks, the slot machines."""\n')
    labels = {ids[i["itemId"]]: i["english"].title() for i in json.load(open(f"{pf}/src/data/items.json"))["items"] if i["itemId"] in ids}
    print(f"GAME_CORNER = {where[GAME_CORNER]!r}\nPRIZE_ROOM = {where[PRIZE_ROOM]!r}\nRESTAURANT = {where[RESTAURANT]!r}   # the man with the Coin Case")
    print(f"COIN_CLERK = ({clerk['x']}, {clerk['y']})\nCOIN_LOTS = {lots!r}   # (coins, yen), in the clerk's menu order")
    print(f"COIN_CASE = ({ids['ITEM_COIN_CASE']}, {flag:#x})   # key item id, FLAG_GOT_COIN_CASE")
    print("PRIZE_CLERKS = [")
    for k, b, m, x, y, rows in out:
        print(f"    ({k!r}, {b}, {m}, {x}, {y}, [")
        for r in rows:
            print(f"        {r!r},")
        print("    ]),")
    print("]")
    prize_items = sorted({r[1] for k, *_x, rows in out if k != "mon" for r in rows})
    print("ITEM_LABELS = {" + ", ".join(f"{i}: {labels.get(i, str(i))!r}" for i in prize_items) + "}")
    sm = open(f"{pf}/src/slot_machine.c").read()
    icon = {n: i for i, n in enumerate(["ICON_7", "ICON_ROCKET", "ICON_PIKACHU", "ICON_PSYDUCK", "ICON_CHERRIES", "ICON_MAGNEMITE", "ICON_SHELLDER"])}
    body = re.search(r"sReelIconAnimByReelAndPos\[NUM_REELS\]\[REEL_LENGTH\] = \{(.*?)\n\};", sm, re.S).group(1)
    reels = [[icon[n] for n in re.findall(r"ICON_\w+", chunk)] for chunk in body.split("}, {")]
    def table(name):
        t = re.search(rf"{name}[^=]*= \{{(.*?)\n\}};", sm, re.S).group(1)
        return [[int(h, 16) for h in re.findall(r"0x[0-9a-fA-F]+", row)] for row in re.findall(r"\{[^{}]*\}", t)]
    chances = [[int(h, 16) for h in re.findall(r"= (0x[0-9a-fA-F]+)", blk)] for blk in re.findall(r"\{\s*\[PAYOUT_NONE\].*?\}", re.search(r"sReelBiasChances.*?\n\};", sm, re.S).group(0), re.S)]
    payouts = [int(n) for n in re.findall(r"=\s+(\d+),?\n", re.search(r"sPayoutTable\[\] = \{(.*?)\};", sm, re.S).group(1))]
    print("# ── slot machine tables (src/slot_machine.c) ──")
    print(f"REEL_ICONS = {reels!r}   # per reel, per position: 0=7 1=Rocket 2=Pikachu 3=Psyduck/Slowpoke 4=Cherries 5=Magnemite/Voltorb 6=Shellder/Staryu")
    print(f"SECOND_REEL_PAIRS = {table('sSecondReelBiasCheckIndices')!r}")
    print(f"THIRD_REEL_LINES = {table('sThirdReelBiasCheckIndices')!r}")
    print(f"ROW_ATTRS = {table('sRowAttributes')!r}   # col1, col2, col3 cell, minimum bet")
    print(f"BIAS_CHANCES = {chances!r}   # per machine: cumulative thresholds (of 0x3FFF) for the payout classes")
    print(f"PAYOUTS = {payouts!r}   # coins per payout class: none, cherries2, cherries3, mag/shell, pika/psy, rocket, 7")
    print("# (x, y, script): the machines you can play; 'Unusable…' ones are out of order\nSLOT_MACHINES = [")
    for s in slots:
        print(f"    {s!r},")
    print("]")


if __name__ == "__main__":
    main()
