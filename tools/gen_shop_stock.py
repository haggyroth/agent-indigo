#!/usr/bin/env python3
"""Generate knowledge/shop_stock.py from a pret/pokefirered checkout.

Usage: python tools/gen_shop_stock.py [path-to-pokefirered] > knowledge/shop_stock.py

SHOPS: every clerk that opens a buy menu — (map_bank, map_id, clerk_x, clerk_y, (item ids…)) — read from the map scripts'
`pokemart <list>` commands, the list's `.2byte ITEM_*` rows and the object event that runs the script.
PRICES / ITEM_LABELS: price and display name of everything any clerk sells (src/data/items.json). SHOP_NAMES: {(bank, id): readable map name}.
"""
import json
import os
import re
import sys


def readable(map_dir: str) -> str:
    s = map_dir.replace("_", " ")
    s = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", s)
    s = s.replace("Mart", "Poké Mart").replace("Department Store", "Dept. Store")
    return s


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    ids = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define (ITEM_\w+)\s+(\d+)", open(f"{pf}/include/constants/items.h").read())}
    items_json = json.load(open(f"{pf}/src/data/items.json"))["items"]
    prices = {ids[i["itemId"]]: i["price"] for i in items_json if i["itemId"] in ids}
    labels = {ids[i["itemId"]]: i["english"].title().replace("Poke", "Poké").replace("'S", "'s") for i in items_json if i["itemId"] in ids}
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    shops, names = [], {}
    for bank, gname in enumerate(groups["group_order"]):
        if gname not in groups:
            continue
        for mid, mdir in enumerate(groups[gname]):
            sc = f"{pf}/data/maps/{mdir}/scripts.inc"
            mj = f"{pf}/data/maps/{mdir}/map.json"
            if not (os.path.exists(sc) and os.path.exists(mj)):
                continue
            text = open(sc).read()
            if "pokemart " not in text:
                continue
            events = json.load(open(mj)).get("object_events", [])
            for blk in re.finditer(r"^(\w+)::\n(.*?)(?=^\w+::|\Z)", text, re.S | re.M):
                label, body = blk.group(1), blk.group(2)
                m = re.search(r"^\s*pokemart (\w+)", body, re.M)
                if not m:
                    continue
                lst = re.search(rf"^{m.group(1)}::\n(.*?)(?=^\s*(?!\.2byte|\.align)\S)", text, re.S | re.M)
                items = [ids[i] for i in re.findall(r"\.2byte (ITEM_\w+)", lst.group(1)) if i in ids and i != "ITEM_NONE"] if lst else []
                ev = next((e for e in events if e.get("script") == label), None)
                if ev and items:
                    shops.append((bank, mid, int(ev["x"]), int(ev["y"]), tuple(items)))
                    names[(bank, mid)] = readable(mdir)
    sold = {i for s in shops for i in s[4]}
    print('"""GENERATED by tools/gen_shop_stock.py from the pokefirered decomp — do not edit.\n'
          'Every clerk with a buy menu: where they stand and what they sell; prices; readable map names."""\n')
    print("SHOPS: list[tuple[int, int, int, int, tuple[int, ...]]] = [")
    for s in shops:
        print(f"    {s!r},")
    print("]\n")
    print("PRICES: dict[int, int] = {")
    for i in sorted(sold):
        print(f"    {i}: {prices.get(i, 0)},")
    print("}\n")
    print("ITEM_LABELS: dict[int, str] = {")
    for i in sorted(sold):
        print(f"    {i}: {labels.get(i, str(i))!r},")
    print("}\n")
    print("SHOP_NAMES: dict[tuple[int, int], str] = {")
    for k in sorted(names):
        print(f"    {k!r}: {names[k]!r},")
    print("}")


if __name__ == "__main__":
    main()
