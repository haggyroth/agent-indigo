"""Regenerate knowledge/vr_data.py from a local pret/pokefirered checkout (Victory Road: three cave floors of Strength-boulder puzzles).

    python tools/gen_victory_road.py [path-to-pokefirered] > knowledge/vr_data.py

Each floor: collision rows (barriers OPEN — the map's OnLoad script closes them while the floor switch is unpressed), the pushable boulders, the floor
switches (a pressure plate: a boulder pushed onto it opens its barrier tiles for good), solid objects (trainers, item balls, the Tutor) and the warps
that fire (cave ladders / holes / exits)."""
import json
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_mansion import BUTTON as _BUTTON, collision_rows, warp_behaviors      # noqa: E402

BUTTON = {**_BUTTON, 0x67: None, 0x69: None, 0x6A: None, 0x6B: None, 0x61: None, 0x66: None}      # cave ladders / holes / exits fire when stepped on
FLOORS = ["VictoryRoad_1F", "VictoryRoad_2F", "VictoryRoad_3F"]
BOULDER = "OBJ_EVENT_GFX_PUSHABLE_BOULDER"
# Route 23's OnTransition (data/maps/Route23/scripts.inc) resets the cave every time you come in: `clearflag FLAG_HIDE_VICTORY_ROAD_3F_BOULDER` (shown),
# `setflag FLAG_HIDE_VICTORY_ROAD_2F_BOULDER` (hidden until the 3F boulder falls through the hole at 3F (34,18) — HandleBoulderFallThroughHole).
SHOWN_AT_START = {"FLAG_HIDE_VICTORY_ROAD_3F_BOULDER"}


def elevations(pf, name):
    """Per-tile elevation as hex digits (the block's top 4 bits). The game blocks a step between two tiles whose elevations differ unless one of
    them is 0 or 15 (a ramp / universal tile) — Victory Road's floors are split into levels that only the 0 tiles join."""
    m = json.load(open(f"{pf}/data/maps/{name}/map.json"))
    layouts = json.load(open(f"{pf}/data/layouts/layouts.json"))["layouts"]
    L = next(x for x in layouts if x.get("id") == m["layout"])
    raw = open(os.path.join(pf, L["blockdata_filepath"]), "rb").read()
    W, H = L["width"], L["height"]
    cells = [struct.unpack_from("<H", raw, 2 * i)[0] for i in range(W * H)]
    return ["".join("%x" % (cells[y * W + x] >> 12) for x in range(W)) for y in range(H)]


def switches(pf, name):
    """[(switch (x, y), (barrier tiles...))] from the map's FloorSwitch<N> scripts + coord events."""
    text = open(f"{pf}/data/maps/{name}/scripts.inc").read()
    m = json.load(open(f"{pf}/data/maps/{name}/map.json"))
    out = []
    for c in m["coord_events"]:
        script = c["script"]
        body = re.search(rf"{script}::\n(.*?)\n\tend", text, re.S).group(1)
        tiles = tuple((int(t.group(1)), int(t.group(2))) for t in re.finditer(r"setmetatile\s+(\d+),\s*(\d+),\s*\w+Floor_Ledge", body))
        out.append(((c["x"], c["y"]), tiles))
    return out


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))["gMapGroup_Dungeons"]
    ids = {n: (1, groups.index(n)) for n in FLOORS}
    out = sys.stdout
    out.write('"""Victory Road floors: collision (barriers open), boulders, floor switches, solid objects, warps. GENERATED by tools/gen_victory_road.py — do not edit."""\n\n')
    out.write("FLOORS: dict = {\n")
    allw = {}
    for name in FLOORS:
        m, rows = collision_rows(pf, name)
        key = ids[name]
        shown = lambda o: o["flag"] == "0" or o["flag"] in SHOWN_AT_START      # noqa: E731
        boulders = [(o["x"], o["y"]) for o in m["object_events"] if o["graphics_id"] == BOULDER and shown(o)]
        later = [(o["x"], o["y"]) for o in m["object_events"] if o["graphics_id"] == BOULDER and not shown(o)]       # revealed later (2F's (33,19): verified live absent at the start)
        solid = [(o["x"], o["y"]) for o in m["object_events"] if o["graphics_id"] != BOULDER]
        out.write(f"    {key}: {{\n        'name': {name.split('_')[1]!r},\n        'rows': (\n")
        for r in rows:
            out.write(f"            {r!r},\n")
        out.write("        ),\n")
        elev = elevations(pf, name)
        out.write("        'elev': (\n" + "".join(f"            {r!r},\n" for r in elev) + "        ),\n")
        holes = [(w["x"], w["y"]) for w in m["warp_events"] if warp_behaviors(pf, name)[(w["x"], w["y"])] == 0x66]
        out.write(f"        'holes': {holes!r},      # fall warps: the player drops to the floor below, a pushed boulder vanishes and reveals one there\n")
        out.write(f"        'later_boulders': {later!r},\n        'boulders': {boulders!r},\n        'switches': {switches(pf, name)!r},\n        'solid': {solid!r},\n    }},\n")
        allw[key] = (name, m["warp_events"])
    out.write("}\n\n")
    out.write("# ((bank, id), x, y) of a warp tile -> ((destination bank, id), arrival x, y) or None for Route 23 (out of the cave). Arrival-only tiles are left out.\n")
    out.write("WARPS: dict = {\n")
    by_map = {f"MAP_VICTORY_ROAD_{n.split('_')[1]}": ids[n] for n in FLOORS}
    for key, (name, wl) in sorted(allw.items()):
        beh = warp_behaviors(pf, name)
        for w in wl:
            if beh[(w["x"], w["y"])] not in BUTTON:
                continue
            dest = w["dest_map"]
            if dest in by_map:
                dname = next(n for n in FLOORS if ids[n] == by_map[dest])
                dw = allw[ids[dname]][1][int(w["dest_warp_id"])]
                out.write(f"    ({key!r}, {w['x']}, {w['y']}): ({by_map[dest]!r}, {dw['x']}, {dw['y']}),\n")
            elif dest == "MAP_ROUTE23":
                out.write(f"    ({key!r}, {w['x']}, {w['y']}): None,\n")
    out.write("}\n")


if __name__ == "__main__":
    main()
