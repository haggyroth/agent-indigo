#!/usr/bin/env python3
"""Regenerate knowledge/rematch_data.py from a local pret/pokefirered checkout (#367).

Usage:
    python tools/gen_rematches.py [path-to-pokefirered] > knowledge/rematch_data.py

Reads `sRematches` (src/vs_seeker.c): every rematchable trainer, its ladder of up to six parties (SKIP = a rung the game does not use), the trainer ids behind them (each party is its
own trainer id, so its defeat flag is TRAINER_FLAGS_START + id), and TryGetRematchTrainerIdGivenGameState's unlock rule per rung (the story flag that opens it).
"""
import os
import re
import sys

PF_DEFAULT = os.path.expanduser("~/Projects/pokefirered")


def parse_defines(path, seed=None):
    """{NAME: int} for every `#define NAME <number | NAME | (NAME + n)>` that resolves (the same small resolver tools/gen_area_sweeps.py uses)."""
    raw = {m.group(1): m.group(2).strip() for m in re.finditer(r"^#define\s+(\w+)\s+(.+?)\s*(?://.*)?$", open(path).read(), re.M)}
    cache = dict(seed or {})

    def val(name, seen=()):
        if name in cache:
            return cache[name]
        expr = raw.get(name)
        if expr is None or name in seen:
            return None
        total = 0
        for tok in re.split(r"\s*\+\s*", expr.strip("() ")):
            tok = tok.strip("() ")
            if re.fullmatch(r"0[xX][0-9a-fA-F]+|\d+", tok):
                total += int(tok, 0)
            else:
                v = val(tok, seen + (name,))
                if v is None:
                    return None
                total += v
        cache[name] = total
        return total
    return {n: v for n in raw if (v := val(n)) is not None}


def main():
    pf = sys.argv[1] if len(sys.argv) > 1 else PF_DEFAULT
    flags = parse_defines(f"{pf}/include/constants/flags.h", seed={"SYS_FLAGS": 0x800})        # SYS_FLAGS is (TRAINER_FLAGS_END + 1) = 0x800 (flags.h says so)
    ids = parse_defines(f"{pf}/include/constants/opponents.h")
    src = open(f"{pf}/src/vs_seeker.c").read()
    table = re.search(r"sRematches\[\]\s*=\s*\{(.*?)^\};", src, re.M | re.S).group(1)
    entries = []
    for m in re.finditer(r"\{\s*\{([^{}]*)\}\s*,\s*MAP\((\w+)\)\s*\}", table, re.S):
        names = [n.strip() for n in m.group(1).split(",") if n.strip()]
        tiers = [None if n == "SKIP" else flags["TRAINER_FLAGS_START"] + ids[n] for n in names]
        first = next(n for n in names if n != "SKIP")
        entries.append((first, m.group(2), tiers))
    unlock = {}
    fn = re.search(r"static void TryGetRematchTrainerIdGivenGameState.*?^\}", src, re.M | re.S).group(0)
    for case, flag in re.findall(r"case (\d+):\s*if \(!FlagGet\((FLAG_\w+)\)\)", fn):
        unlock[int(case)] = flags[flag]
    out = ['"""GENERATED by tools/gen_rematches.py from the pret/pokefirered decomp — do not edit. (#367)',
           "",
           "REMATCHES: one (trainer, map constant, [defeat flag per rung or None]) per rematchable trainer; a rung's flag is TRAINER_FLAGS_START + the rung's trainer id, set once that party is",
           "beaten. TIER_UNLOCK: rung index -> the story flag that must be set before the game offers that rung (rung 0 is the trainer's first fight, always open).",
           '"""',
           "", f"TIER_UNLOCK = {dict(sorted(unlock.items()))!r}", "", "REMATCHES = ["]
    for first, mp, tiers in entries:
        out.append(f"    ({first!r}, {mp!r}, {tiers!r}),")
    out.append("]")
    sys.stdout.write("\n".join(out) + "\n")
    print(f"# {len(entries)} rematchable trainers, unlock rules {unlock}", file=sys.stderr)


if __name__ == "__main__":
    main()
