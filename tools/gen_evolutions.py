#!/usr/bin/env python3
"""Generate knowledge/evolutions.py from a pret/pokefirered checkout.

Usage: python tools/gen_evolutions.py [path-to-pokefirered] > knowledge/evolutions.py

EVO_BY_ITEM maps (species id, item id) -> evolved species id for item-triggered evolutions (the five stones). Used to tell
the model which party member can use which stone in its Bag.
"""
import os
import re
import sys


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    sp = {m.group(1): int(m.group(2)) for m in
          re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    it = {m.group(1): int(m.group(2)) for m in
          re.finditer(r"#define ITEM_(\w+)\s+(\d+)", open(f"{pf}/include/constants/items.h").read())}
    out = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\]\s*=\s*\{(.*?\})\},?\n", open(f"{pf}/src/data/pokemon/evolution.h").read(), re.S):
        for kind, item, target in re.findall(r"\{(EVO_ITEM),\s*ITEM_(\w+),\s*SPECIES_(\w+)\}", m.group(2)):
            if m.group(1) in sp and item in it and target in sp:
                out[(sp[m.group(1)], it[item])] = (sp[target], f"{m.group(1)}->{target} via {item}")
    print('"""GENERATED by tools/gen_evolutions.py from the pokefirered decomp — do not edit.\n'
          '(species id, item id) -> evolved species id, for item-triggered evolutions."""\n')
    print("EVO_BY_ITEM: dict[tuple[int, int], int] = {")
    for k in sorted(out):
        print(f"    {k!r}: {out[k][0]},  # {out[k][1]}")
    print("}")


if __name__ == "__main__":
    main()
