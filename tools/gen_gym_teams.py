#!/usr/bin/env python3
"""Generate knowledge/gym_teams.py from a pret/pokefirered checkout.

Usage: python tools/gen_gym_teams.py [path-to-pokefirered] > knowledge/gym_teams.py

TRAINER_TEAMS maps a Gym Leader / Elite Four member name (as knowledge.leafgreen_data spells it) to their first-battle party:
[(species id, level, (move names…)), …]. knowledge.team uses it to ask "can my team hit this leader's Pokémon super
effectively, and who resists their moves?".
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from game.constants import MOVE_NAMES   # noqa: E402

PARTIES = {"Brock": "LeaderBrock", "Misty": "LeaderMisty", "Lt. Surge": "LeaderLtSurge", "Erika": "LeaderErika",
           "Koga": "LeaderKoga", "Sabrina": "LeaderSabrina", "Blaine": "LeaderBlaine", "Giovanni": "LeaderGiovanni",
           "Lorelei": "EliteFourLorelei", "Bruno": "EliteFourBruno", "Agatha": "EliteFourAgatha",
           "Lance": "EliteFourLance",
           # The Champion carries the starter that beats yours: "Gary (Squirtle)" is the team you meet if you picked Charmander.
           "Gary (Squirtle)": "ChampionFirstSquirtle", "Gary (Bulbasaur)": "ChampionFirstBulbasaur",
           "Gary (Charmander)": "ChampionFirstCharmander"}


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    sp = {m.group(1): int(m.group(2)) for m in
          re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    mv = {m.group(1): int(m.group(2)) for m in
          re.finditer(r"#define MOVE_(\w+)\s+(\d+)", open(f"{pf}/include/constants/moves.h").read())}
    txt = open(f"{pf}/src/data/trainer_parties.h").read()
    out = {}
    for leader, sym in PARTIES.items():
        m = re.search(rf"sParty_{sym}\[\] = \{{(.*?)\n\}};", txt, re.S)
        mons = []
        for lvl, species, moves in re.findall(
                r"\.lvl = (\d+),\s*(?:\.species = SPECIES_(\w+),)\s*(?:\.heldItem = \w+,\s*)?\.moves = \{([^}]*)\}", m.group(1)):
            names = tuple(MOVE_NAMES[mv[x[5:]]] for x in re.findall(r"MOVE_\w+", moves) if x != "MOVE_NONE" and mv.get(x[5:]) in MOVE_NAMES)
            mons.append((sp[species], int(lvl), names))
        out[leader] = mons
    print('"""GENERATED by tools/gen_gym_teams.py from the pokefirered decomp — do not edit.\n'
          'Gym Leader / Elite Four name -> first-battle party [(species id, level, moves)]."""\n')
    print("TRAINER_TEAMS: dict[str, list[tuple[int, int, tuple[str, ...]]]] = {")
    for k, v in out.items():
        print(f"    {k!r}: [")
        for row in v:
            print(f"        {row!r},")
        print("    ],")
    print("}")


if __name__ == "__main__":
    main()
