#!/usr/bin/env python3
"""Generate knowledge/dex_sources.py from a pret/pokefirered checkout: where Kanto species come from OTHER than the wild.

Usage: python tools/gen_dex_sources.py [path-to-pokefirered] > knowledge/dex_sources.py

EVOLVES_FROM: species id -> (pre-evolution id, how: 'level 16' / 'a trade' / 'Moon Stone' / 'high friendship') for the 151 Kanto species (gEvolutionTable);
TRADES: species id -> (species the NPC wants, place) for the single-version in-game trades (data/ingame_trades.h + the map script that sets VAR_0x8008). Gifts, fossils,
prizes and static encounters are curated in knowledge/dex_plan.py (each line verified against a `givemon` / `setvar VAR_TEMP_1, SPECIES_*` in the decomp)."""
import os
import re
import sys

PLACES = {"MR_MIME": "Route 2 house (the scientist)", "JYNX": "Cerulean City, house 3", "FARFETCHD": "Vermilion City, house 2",
          "LICKITUNG": "Route 18 gatehouse, 2F", "ELECTRODE": "Cinnabar Pokémon Lab, the lounge", "TANGELA": "Cinnabar Pokémon Lab, the lounge",
          "SEEL": "Cinnabar Pokémon Lab, the experiment room"}


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    sp = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    items = {m.group(1): m.group(1).replace("_", " ").title() for m in re.finditer(r"#define ITEM_(\w+)\s+\d+", open(f"{pf}/include/constants/items.h").read())}
    evo = {}
    for part in re.split(r"\[SPECIES_", open(f"{pf}/src/data/pokemon/evolution.h").read())[1:]:      # one chunk per species (a row can span lines: Eevee, Gloom, Poliwhirl…)
        src = sp.get(part.split("]", 1)[0], 0)
        for e in re.finditer(r"\{(EVO_\w+),\s*(\w+),\s*SPECIES_(\w+)\}", part):
            kind, param, dst = e.groups()
            if not (1 <= src <= 151 and 1 <= sp.get(dst, 0) <= 151):
                continue
            how = {"EVO_TRADE": "a trade", "EVO_FRIENDSHIP": "high friendship"}.get(kind)
            if kind == "EVO_LEVEL":
                how = f"level {int(param)}"
            elif kind == "EVO_ITEM":
                how = items.get(param.replace("ITEM_", ""), param)
            elif kind == "EVO_TRADE_ITEM":
                how = "a trade holding " + items.get(param.replace("ITEM_", ""), param)
            evo[sp[dst]] = (src, how or kind)
    trades = {}
    txt = open(f"{pf}/src/data/ingame_trades.h").read()
    for part in re.split(r"\[INGAME_TRADE_", txt)[1:]:                      # one chunk per trade (the last one has no closing neighbour)
        names = re.findall(r"\.species = SPECIES_(\w+)", part)
        wants = re.findall(r"\.requestedSpecies = SPECIES_(\w+)", part)
        if len(names) == 1 and names[0] in sp and wants and names[0] in PLACES:
            trades[sp[names[0]]] = (sp[wants[0]], PLACES[names[0]])
    w = sys.stdout.write
    w('"""Where Kanto species come from besides the wild. GENERATED by tools/gen_dex_sources.py from the pokefirered decomp — do not edit."""\n\n')
    w("# species id -> (pre-evolution id, how)\nEVOLVES_FROM: dict[int, tuple[int, str]] = {\n")
    for k in sorted(evo):
        w(f"    {k}: {evo[k]!r},\n")
    w("}\n\n# species id -> (species id the NPC wants, place)\nTRADES: dict[int, tuple[int, str]] = {\n")
    for k in sorted(trades):
        w(f"    {k}: {trades[k]!r},\n")
    w("}\n")


if __name__ == "__main__":
    main()
