#!/usr/bin/env python3
"""Generate knowledge/wild_locations.py from a pret/pokefirered checkout.

Usage: python tools/gen_wild_locations.py [path-to-pokefirered] > knowledge/wild_locations.py

WILD_LOCATIONS maps a species id to where it appears in LeafGreen: [(map bank, map id, method, min level, max level)] with
method "grass", "surf", "rock smash", "old rod", "good rod" or "super rod" (the fishing table's ten slots: 0-1 are the Old Rod's, 2-4 the Good Rod's,
5-9 the Super Rod's — src/wild_encounter.c ChooseWildMonIndex_Fishing; a better rod can also reel in the lower slots, so "good rod" means "needs at least a Good Rod"). knowledge.team uses it to tell the model WHERE to find a Pokémon it
wants (never from memory of another game version).
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

SEVII = ("_ISLAND", "ICEFALL", "ROCKET_WAREHOUSE", "LOST_CAVE", "PATTERN_BUSH", "ALTERING", "TANOBY", "MEMORIAL",
         "RESORT_GORGEOUS", "WATER_LABYRINTH", "BERRY_FOREST", "CAPE_BRINK", "BOND_BRIDGE", "TREASURE_BEACH",
         "KINDLE_ROAD", "CANYON", "RUIN_VALLEY", "OUTCAST", "SEVII")
FIELDS = {"land_mons": "grass", "water_mons": "surf", "rock_smash_mons": "rock smash", "fishing_mons": "fish"}
ROD_BY_SLOT = ("old rod",) * 2 + ("good rod",) * 3 + ("super rod",) * 5


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    c2gn = {}
    for gi, gname in enumerate(groups["group_order"]):
        if not gname.startswith("gMapGroup_"):
            continue
        for ni, dname in enumerate(groups[gname]):
            mj = f"{pf}/data/maps/{dname}/map.json"
            if os.path.exists(mj):
                c2gn[json.load(open(mj))["id"]] = (gi, ni)
    ids = {}
    import re
    for m in re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read()):
        ids[m.group(1)] = int(m.group(2))
    wild = json.load(open(f"{pf}/src/data/wild_encounters.json"))["wild_encounter_groups"][0]
    out: dict[int, dict] = {}
    labels: dict[tuple[int, int], str] = {}
    for e in wild["encounters"]:
        if not e["base_label"].endswith("LeafGreen"):
            continue
        gn = c2gn.get(e["map"])
        if gn is None:
            continue
        if any(tok in e["map"] for tok in SEVII):        # the Sevii Islands are not part of the Kanto story
            continue
        labels[gn] = e["map"].replace("MAP_", "").replace("_", " ").title().replace("Digletts", "Diglett's").replace("Ss ", "S.S. ")
        for fld, method in FIELDS.items():
            for slot, mon in enumerate((e.get(fld) or {}).get("mons", [])):
                sid = ids.get(mon["species"].replace("SPECIES_", ""))
                if not sid or sid > 151:             # Kanto Pokémon only (Gen II appear only on the Sevii Islands)
                    continue
                key = (gn[0], gn[1], ROD_BY_SLOT[slot] if method == "fish" else method)
                lo, hi = out.setdefault(sid, {}).get(key, (999, 0))
                out[sid][key] = (min(lo, mon["min_level"]), max(hi, mon["max_level"]))
    print('"""GENERATED by tools/gen_wild_locations.py from the pokefirered decomp — do not edit.\n'
          'species id -> [(map bank, map id, method, min level, max level)] in LeafGreen."""\n')
    print("MAP_LABELS: dict[tuple[int, int], str] = {")
    for k in sorted(labels):
        print(f"    {k!r}: {labels[k]!r},")
    print("}\n")
    print("WILD_LOCATIONS: dict[int, list[tuple[int, int, str, int, int]]] = {")
    for sid in sorted(out):
        rows = [(b, i, meth, lo, hi) for (b, i, meth), (lo, hi) in sorted(out[sid].items())]
        print(f"    {sid}: {rows!r},")
    print("}")


if __name__ == "__main__":
    main()
