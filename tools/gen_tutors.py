#!/usr/bin/env python3
"""Generate knowledge/tutors.py (move tutors on the Kanto mainland) from a pret/pokefirered checkout.

Usage: python tools/gen_tutors.py [path-to-pokefirered] > knowledge/tutors.py

TUTOR_MOVES: tutor index (TUTOR_MOVE_*) -> move name; LEARNSETS: species id -> bitmask (bit = tutor index); TUTORS: key -> (move name, tutor index, (bank, id), npc (x, y),
FLAG_TUTOR_* flag, display name of the place). Each tutor teaches its move once (the flag), free of charge, to any party Pokémon whose learnset has the bit."""
import glob
import json
import os
import re
import sys

# tutor key -> (script suffix of the NPC, tutor move constant, FLAG_TUTOR_ name, place label, extra requirement note)
TUTORS = [
    ("mega_punch", "Route4_EventScript_MegaPunchTutor", "MEGA_PUNCH", "FLAG_TUTOR_MEGA_PUNCH", "Route 4 (east side)", ""),
    ("mega_kick", "Route4_EventScript_MegaKickTutor", "MEGA_KICK", "FLAG_TUTOR_MEGA_KICK", "Route 4 (east side)", ""),
    ("softboiled", "CeladonCity_EventScript_SoftboiledTutor", "SOFT_BOILED", "FLAG_TUTOR_SOFT_BOILED", "Celadon City", ""),
    ("counter", "CeladonCity_DepartmentStore_3F_EventScript_CounterTutor", "COUNTER", "FLAG_TUTOR_COUNTER", "Celadon Dept. Store 3F", ""),
    ("metronome", "CinnabarIsland_PokemonLab_ResearchRoom_EventScript_MetronomeTutor", "METRONOME", "FLAG_TUTOR_METRONOME", "Cinnabar Pokémon Lab (research room)", ""),
    ("substitute", "FuchsiaCity_EventScript_SubstituteTutor", "SUBSTITUTE", "FLAG_TUTOR_SUBSTITUTE", "Fuchsia City", ""),
    ("seismic_toss", "PewterCity_Museum_1F_EventScript_SeismicTossTutor", "SEISMIC_TOSS", "FLAG_TUTOR_SEISMIC_TOSS", "Pewter Museum 1F", "the Museum charges ¥50 at the door; the tutor is at the back"),
    ("rock_slide", "RockTunnel_B1F_EventScript_RockSlideTutor", "ROCK_SLIDE", "FLAG_TUTOR_ROCK_SLIDE", "Rock Tunnel B1F", ""),
    ("thunder_wave", "SilphCo_2F_EventScript_ThunderWaveTutor", "THUNDER_WAVE", "FLAG_TUTOR_THUNDER_WAVE", "Silph Co. 2F", ""),
    ("double_edge", "VictoryRoad_2F_EventScript_DoubleEdgeTutor", "DOUBLE_EDGE", "FLAG_TUTOR_DOUBLE_EDGE", "Victory Road 2F", ""),
    ("dream_eater", "ViridianCity_EventScript_DreamEaterTutor", "DREAM_EATER", "FLAG_TUTOR_DREAM_EATER", "Viridian City", ""),
    ("mimic", "SaffronCity_CopycatsHouse_2F_EventScript_Copycat", "MIMIC", "FLAG_TUTOR_MIMIC", "Saffron Copycat's House 2F", "needs a Poké Doll in the bag"),
]


def main():
    pf = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/pokefirered")
    sp = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define SPECIES_(\w+)\s+(\d+)", open(f"{pf}/include/constants/species.h").read())}
    idx = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define TUTOR_(MOVE_\w+)\s+(\d+)", open(f"{pf}/include/constants/party_menu.h").read())}
    flags = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"#define (FLAG_TUTOR_\w+)\s+(0x[0-9A-Fa-f]+)", open(f"{pf}/include/constants/flags.h").read())}
    groups = json.load(open(f"{pf}/data/maps/map_groups.json"))
    order = groups["group_order"]

    def map_id(name):
        for gi, gn in enumerate(order):
            if name in groups.get(gn, []):
                return gi, groups[gn].index(name)
    npcs = {}
    for f in glob.glob(f"{pf}/data/maps/*/map.json"):
        m = json.load(open(f))
        name = f.split("/")[-2]
        for o in m.get("object_events", []):
            npcs[o.get("script", "")] = (map_id(name), (int(o["x"]), int(o["y"])))
    moves = {}
    for m in re.finditer(r"\[TUTOR_(MOVE_\w+)\]\s*=\s*MOVE_(\w+)", open(f"{pf}/src/data/pokemon/tutor_learnsets.h").read()):
        moves[idx[m.group(1)]] = m.group(2).replace("_", " ").title()
    txt = open(f"{pf}/src/data/pokemon/tutor_learnsets.h").read()
    learn = {}
    for m in re.finditer(r"\[SPECIES_(\w+)\]\s*=\s*([^\[]*?),\s*\n\s*\n", txt + "\n\n", re.S):
        name, body = m.group(1), m.group(2)
        if name not in sp or sp[name] == 0:
            continue
        mask = 0
        for t in re.finditer(r"TUTOR\((MOVE_\w+)\)", body):
            mask |= 1 << idx[t.group(1)]
        if mask:
            learn[sp[name]] = mask
    w = sys.stdout.write
    w('"""Kanto move tutors: GENERATED by tools/gen_tutors.py from the pokefirered decomp — do not edit."""\n\n')
    w("# tutor index -> move name\nTUTOR_MOVES: dict[int, str] = {\n")
    for k in sorted(moves):
        w(f"    {k}: {moves[k]!r},\n")
    w("}\n\n# species id -> bitmask (bit = tutor index)\nLEARNSETS: dict[int, int] = {\n")
    for k in sorted(learn):
        w(f"    {k}: {learn[k]:#x},\n")
    w("}\n\n# key -> (move name, tutor index, (bank, id), npc (x, y), FLAG_TUTOR_* flag, place, requirement note)\nTUTORS: dict[str, tuple] = {\n")
    for key, script, const, flag, place, note in TUTORS:
        mp, pos = npcs[script]
        w(f"    {key!r}: ({moves[idx['MOVE_' + const]]!r}, {idx['MOVE_' + const]}, {mp!r}, {pos!r}, {flags[flag]:#x}, {place!r}, {note!r}),\n")
    w("}\n")


if __name__ == "__main__":
    main()
