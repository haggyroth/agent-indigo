"""The tool table in CLAUDE.md, generated from agent/tools.py (so it cannot drift: tests/test_tool_docs.py fails if the
checked-in block differs). Regenerate with `python tools/gen_tool_docs.py`."""
import re

START, END = "<!-- TOOLS:START (generated by tools/gen_tool_docs.py — do not edit) -->", "<!-- TOOLS:END -->"


def _first_sentence(text: str) -> str:
    """The first sentence — or the first two when the first is very short ('Use a Bag item.')."""
    parts = re.findall(r".+?[.!?](?=\s|$)", text.strip())
    out = parts[0] if parts else text.strip()
    if len(out) < 45 and len(parts) > 1:
        out += " " + parts[1]
    return out.replace("|", "\\|")


def _args(tool: dict) -> str:
    props = tool["function"]["parameters"].get("properties", {})
    req = set(tool["function"]["parameters"].get("required", []))
    return ", ".join(f"{k}{'' if k in req else '?'}" for k in props) or "—"


def render_markdown() -> str:
    from agent.tools import TOOLS, tools_for
    from game.state import GameContext
    battle = {t["function"]["name"] for t in tools_for(GameContext.IN_BATTLE)}
    field = {t["function"]["name"] for t in tools_for(GameContext.OVERWORLD)}
    rows = ["| Tool | Offered in | Arguments | What it does |", "|---|---|---|---|"]
    for t in TOOLS:
        n = t["function"]["name"]
        where = "battle + overworld" if n in battle and n in field else "battle" if n in battle else \
            "overworld" if n in field else "menus / naming screens"
        rows.append(f"| `{n}` | {where} | {_args(t)} | {_first_sentence(t['function']['description'])} |")
    note = ("Other contexts (menus, dialog, transitions, unknown) are offered every tool. `?` marks an optional argument. "
            f"{len(TOOLS)} tools in total.")
    return "\n".join([START, *rows, "", note, END])
